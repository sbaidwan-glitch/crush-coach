class Task(SQLModel, table=True):
    id: int | None = Field(default=None, primary_key=True)
    code: str = Field(index=True, unique=True)  # e.g. "M04"
    title: str
    subsystem: str
    task_type: str  # Fabricate, Design, or Validate
    stage: str
    owner: str | None = None
    status: str = "todo"
    # Free-text fields from the team's tracker; the coach and task page show them.
    description: str | None = None
    dependencies: str | None = None
    exploratory_questions: str | None = None
    skills: str | None = None
    requirements: str | None = None
    people_to_ask: str | None = None
    documentation: str | None = None
    due_date: str | None = None  # text on purpose: the tracker has "Week 3", "TBD", ...


class CoachMessage(SQLModel, table=True):
    """One turn of a task's coach conversation."""

    __tablename__ = "coach_message"

    id: int | None = Field(default=None, primary_key=True)
    task_id: int = Field(foreign_key="task.id", index=True)
    member: str
    role: str  # "user" or "assistant"
    content: str
    # JSON: {"sources": [{"title", "link", "modified"}], "notes": [str]}
    meta: str | None = None
    created_at: datetime = Field(default_factory=utc_now, index=True)


class LlmCall(SQLModel, table=True):
    """One model call, for the cost-benefit analysis. Never stores prompt text."""

    __tablename__ = "llm_call"

    id: int | None = Field(default=None, primary_key=True)
    task_id: int | None = Field(default=None, foreign_key="task.id", index=True)
    member: str
    model: str
    input_tokens: int | None = None
    output_tokens: int | None = None
    latency_ms: int
    cost: float | None = None  # only when the response provides it
    status: str  # ok, budget_exceeded, rate_limited, timeout, error
    created_at: datetime = Field(default_factory=utc_now)


# --- local index of the team's shared Drive (see drive_index.py) ---

# The full-text column is generated by Postgres from the heading and text, so it
# can never drift from them. Heading words weigh more than body words.
CHUNK_SEARCH_VECTOR_SQL = (
    "setweight(to_tsvector('english', coalesce(heading, '')), 'A') || "
    "setweight(to_tsvector('english', text), 'C')"
)


class DriveFile(SQLModel, table=True):
    """One file or folder in the shared drive: metadata, plus how its text went."""

    __tablename__ = "drive_file"

    id: int | None = Field(default=None, primary_key=True)
    drive_id: str = Field(index=True, unique=True)  # Google's file id
    name: str
    mime_type: str
    parent_id: str | None = None  # Google id of the folder it sits in
    folder_path: str = "/"  # "Shared drive / Mechanical / CAD"; "/" if unknown
    modified_time: datetime | None = None  # naive UTC, like every timestamp here
    web_link: str | None = None
    size: int | None = Field(default=None, sa_column=Column(BigInteger))
    kind: str = Field(index=True)  # doc, sheet, pdf, cad, folder, other
    text_status: str  # ok, skipped, error
    text_reason: str | None = None  # why it was skipped, failed, or cut short
    last_indexed_at: datetime = Field(default_factory=utc_now)


class DriveChunk(SQLModel, table=True):
    """A 300-600 word piece of a file's text, searchable with Postgres full text."""

    __tablename__ = "drive_chunk"
    # GIN is for Postgres; SQLite (tests) just gets a plain index on a column that
    # stays empty, and searches with LIKE instead.
    __table_args__ = (
        Index("ix_drive_chunk_search_vector", "search_vector", postgresql_using="gin"),
    )

    id: int | None = Field(default=None, primary_key=True)
    file_id: int = Field(
        sa_column=Column(
            Integer,
            ForeignKey("drive_file.id", ondelete="CASCADE"),
            index=True,
            nullable=False,
        )
    )
    position: int  # 0, 1, 2... in reading order
    heading: str | None = None  # the tab or section it came from
    text: str
    # Never set from Python: Postgres fills it in (SQLite leaves it empty).
    search_vector: str | None = Field(
        default=None,
        sa_column=Column(
            TSVECTOR().with_variant(Text(), "sqlite"),
            Computed(CHUNK_SEARCH_VECTOR_SQL, persisted=True),
        ),
    )


class SyncState(SQLModel, table=True):
    """The one row (id 1) that remembers where the Drive sync got to."""

    __tablename__ = "sync_state"

    id: int | None = Field(default=None, primary_key=True)
    page_token: str | None = None  # Drive changes feed: where the next sync starts
    last_full_sync: datetime | None = None
    last_incremental_sync: datetime | None = None
    file_count: int = 0  # files and folders in the index
    chunk_count: int = 0
    error_count: int = 0  # files whose text could not be read
    running_since: datetime | None = None  # set while a sync runs; stale after 2 h
    last_error: str | None = None  # why the last sync failed, if it did
