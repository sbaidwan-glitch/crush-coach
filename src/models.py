def normalize_status(value: str | None) -> str | None:
    """The status a word means (todo, in_progress, needs_review, done), or None."""
    word = " ".join((value or "").split()).casefold()
    if word in STATUSES:
        return word
    return STATUS_ALIASES.get(word)

